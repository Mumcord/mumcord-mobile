# Generates every app icon asset of both apps from the masters in design/icon/. Nothing the
# script writes is edited by hand; run it again after replacing a master.
# Needs rsvg-convert (librsvg), ImageMagick 7 (`magick`) and python3.
#
#   Android  android/app/src/main/res/drawable-nodpi/ic_launcher_foreground.png   colour mark
#            android/app/src/main/res/drawable-nodpi/ic_launcher_monochrome.png   themed icon layer
#            android/app/src/main/res/drawable/ic_launcher_background.xml         tile gradient
#            ic_call_session.png / ic_message.png (call and notify modules)       notification glyph
#   iOS      ios/Mumcord/Resources/Assets.xcassets/AppIcon.appiconset/AppIcon.png
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
master=$root/design/icon
res=$root/android/app/src/main/res
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Adaptive icon layers are 108 dp; at xxxhdpi that is 432 px. Launchers mask everything outside
# the inner 66 dp circle (264 px), so the mark has to fit inside that circle. The box size of
# the mark below is checked against the circle after rendering. The silhouette has a thick
# outline that makes it larger than the colour mark, so it gets a smaller box.
canvas=432

# A mark rendered into a transparent square canvas, centred.
layer() { # <svg> <output> <box size in px>
    rsvg-convert -w "$3" -h "$3" "$1" -o "$work/mark.png"
    magick "$work/mark.png" -background none -gravity center -extent "${canvas}x${canvas}" "$2"
}

# Fails when any visible pixel of a layer lies outside the 66 dp safe circle.
check_safe_zone() { # <png>
    python3 -I - "$1" "$canvas" <<'PY'
import subprocess, sys
png, canvas = sys.argv[1], int(sys.argv[2])
out = subprocess.run(["magick", png, "-alpha", "extract", "-threshold", "5%", "-depth", "8", "txt:-"],
                     check=True, capture_output=True, text=True).stdout
limit = canvas * 66 / 108 / 2
worst = 0.0
for line in out.splitlines()[1:]:
    if "#FFFFFF" in line:
        xy = line.split(":")[0].split(",")
        worst = max(worst, ((int(xy[0]) + .5 - canvas / 2) ** 2 + (int(xy[1]) + .5 - canvas / 2) ** 2) ** .5)
if worst > limit:
    sys.exit(f"{png}: mark reaches {worst:.0f} px from the centre, the safe circle has {limit:.0f} px")
PY
}

# --- Android launcher icon ------------------------------------------------------------------

mkdir -p "$res/drawable-nodpi" "$res/drawable"

# Foreground: the logo without its tile. Its body is dark purple for light pages; on the dark
# tile it needs the light purple the logo uses in dark mode.
sed 's/fill: #2a0a7a/fill: #e1d0fd/' "$master/mumcord-logo.svg" > "$work/logo-on-dark.svg"
layer "$work/logo-on-dark.svg" "$res/drawable-nodpi/ic_launcher_foreground.png" 224
check_safe_zone "$res/drawable-nodpi/ic_launcher_foreground.png"

# Themed icon layer: the flat silhouette of the tray master (outline group only), in one colour;
# the launcher tints it.
python3 -I - "$master/mumcord-tray.svg" "$work/silhouette.svg" <<'PY'
import sys
s = open(sys.argv[1]).read()
open(sys.argv[2], "w").write(s[:s.index('<g fill="#fff">')] + "</svg>")
PY
layer "$work/silhouette.svg" "$res/drawable-nodpi/ic_launcher_monochrome.png" 212
check_safe_zone "$res/drawable-nodpi/ic_launcher_monochrome.png"

# Background: the tile's own gradient (colours read from the master), as a vector drawable.
stop() { grep -o "<stop offset=\"$1\" stop-color=\"#[0-9a-f]*\"" "$master/mumcord-icon.svg" | head -1 | grep -o '#[0-9a-f]*'; }
cat > "$res/drawable/ic_launcher_background.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: AGPL-3.0-only -->
<!-- Generated by scripts/generate-app-icons.sh from design/icon/mumcord-icon.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor" xmlns:aapt="http://schemas.android.com/aapt">
            <gradient
                android:type="radial"
                android:centerX="54"
                android:centerY="54"
                android:gradientRadius="76"
                android:startColor="$(stop 0)"
                android:endColor="$(stop 1)" />
        </aapt:attr>
    </path>
</vector>
XML

# --- Android notification glyph: flat white silhouette, one PNG per density -------------------

# A vector drawable would need the silhouette path cut down to 800 characters (lint rule
# VectorPath), which would mean redrawing it; the status bar only uses the alpha channel anyway.
sed 's/#11012f/#fff/g' "$work/silhouette.svg" > "$work/silhouette-white.svg"
rm -f "$root/android/platform/call/src/main/res/drawable/ic_call_session.xml" \
      "$root/android/platform/notify/src/main/res/drawable/ic_message.xml"
for density in mdpi:24 hdpi:36 xhdpi:48 xxhdpi:72 xxxhdpi:96; do
    dir=drawable-${density%%:*}
    size=${density##*:}
    for target in platform/call/src/main/res/ic_call_session platform/notify/src/main/res/ic_message; do
        out=$root/android/${target%/*}/$dir
        mkdir -p "$out"
        rsvg-convert -w "$size" -h "$size" "$work/silhouette-white.svg" -o "$out/${target##*/}.png"
    done
done

# --- iOS app icon ---------------------------------------------------------------------------

# The system applies the rounded corners itself, so the tile goes in as a full square, and the
# App Store refuses an alpha channel, so it is flattened onto the tile's own colour.
sed 's/rx="350"/rx="0"/g' "$master/mumcord-icon.svg" > "$work/icon-square.svg"
ios=$root/ios/Mumcord/Resources/Assets.xcassets/AppIcon.appiconset
mkdir -p "$ios"
rsvg-convert -w 1024 -h 1024 "$work/icon-square.svg" -o "$work/ios.png"
magick "$work/ios.png" -background "$(stop 0)" -alpha remove -alpha off "$ios/AppIcon.png"
